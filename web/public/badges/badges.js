export const byAbbr = Object.fromEntries(TEAMS.map(t => [t.abbr, t]));

/** Inline SVG string for a team badge. */
export function badgeSVG(abbr, size = 40) {
  const t = byAbbr[abbr];
  if (!t) return "";
  const rows = GLYPHS[t.glyph], r = [];
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++)
    if (rows[y][x] === "1") r.push(`<rect x="${x+1}" y="${y+1}" width="1" height="1"/>`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 10 10" shape-rendering="crispEdges"><rect width="10" height="10" fill="${t.primary}"/><g fill="${t.secondary}">${r.join("")}</g></svg>`;
}

/** CSS box-shadow pixel-art badge (no images). Returns {tile, px, shadow, background}. */
export function badgeShadow(abbr, px = 4) {
  const t = byAbbr[abbr];
  if (!t) return null;
  const rows = GLYPHS[t.glyph], parts = [];
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++)
    if (rows[y][x] === "1") parts.push(`${(x+1)*px}px ${(y+1)*px}px 0 0 ${t.secondary}`);
  return { tile: 10 * px, px, shadow: parts.join(","), background: t.primary };
}
